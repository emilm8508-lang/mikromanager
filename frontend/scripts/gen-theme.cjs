// Writes src/theme.css: every Tailwind colour as a CSS variable (light) and the same scale reversed for the dark theme
// (shade 50 <-> 950, 100 <-> 900 ... 500 stays), plus "white" -> slate-900 and slate-950 behind it. Run after changing FAMILIES:
//   node scripts/gen-theme.cjs
const colors = require('tailwindcss/colors')
const fs = require('fs')
const FAMILIES = ['slate', 'gray', 'zinc', 'neutral', 'stone', 'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose']
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
const rgb = hex => { const h = hex.replace('#', ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)).join(' ') }
let light = ':root {\n  --c-white: 255 255 255;\n', dark = '.dark {\n  color-scheme: dark;\n  --c-white: ' + rgb(colors.slate[900]) + ';\n'
for (const f of FAMILIES) for (const s of SHADES) {
  light += `  --c-${f}-${s}: ${rgb(colors[f][s])};\n`
  dark += `  --c-${f}-${s}: ${rgb(colors[f][1000 - s])};\n`
}
fs.writeFileSync(__dirname + '/../src/theme.css', '/* generated by scripts/gen-theme.cjs - do not edit */\n' + light + '}\n' + dark + '}\n')
console.log('theme.css written')
